        let t2 = t1 + 20 + g + 1;
        sink.write_byte(0x0D, t2);
        let out = drain_str(&mut sink);
        assert!(out.contains("OK"), "{out:?}");
        assert!(state.lock().unwrap().from_guest.is_empty());
