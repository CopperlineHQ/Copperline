/// Longest command line a real Hayes modem accepts before giving up; a line
/// that grows past this without a terminating CR is discarded rather than
/// grown without bound.
const MAX_LINE_LEN: usize = 255;

/// Cap on modem-generated bytes (echo plus result-code text) waiting for the
/// guest to read them. Unlike [`crate::serial::CHANNEL_OUTPUT_CAPACITY`]
/// this queue only ever holds short protocol strings ("\r\nOK\r\n" and
/// friends) between guest reads, so the cap is never expected to bind in
/// practice; it exists only so a guest that stops reading altogether cannot
/// make this queue grow forever.
const OUT_QUEUE_CAPACITY: usize = 4096;

/// Errors ATD reports as distinct result codes: a refused connection is
/// BUSY, anything else NO CARRIER.
#[derive(Debug)]
pub(crate) enum DialError {
    Refused,
    Unreachable,
}

/// Construction-time options for [`ModemSerialSink::new_tcp`] -- what the
/// host configuration decides once, as opposed to AT-settable state a guest
/// program controls at runtime.
#[derive(Default, Clone)]
pub struct ModemOptions {
    /// Bind and answer inbound calls on "host:port". `None`: dial-out only
    /// unless a stored profile's `AT*L` port takes over (see
    /// [`ModemSerialSink::new_tcp`]) -- nothing ever RINGs, ATA always
    /// reports NO CARRIER.
    pub listen: Option<String>,
    /// `[serial] telnet`: an explicit `true` here always wins over whatever
    /// a stored profile's `AT*T` says (see `profile.rs`'s doc comment); a
    /// `false` cannot be told apart from "unset", so it defers to the
    /// profile -- the same limitation [`crate::config::SerialConfig::telnet`]
    /// already has (its default and its explicit-off both read `false`).
    pub telnet: bool,
    /// `[serial.phonebook]`: dialable numbers an `ATD`/`ATDT` with an
    /// all-digit target resolves through, number -> "host:port" (or a bare
    /// host, which dials the modem's default port).
    pub phonebook: Vec<(String, String)>,
}

/// The byte transport a [`ModemSerialSink`] dials out on. Abstracted so the
/// state machine can be exercised in tests without opening real sockets;
/// [`TcpModemTransport`] is the production implementation.
pub(crate) trait ModemTransport: Send {
    /// Dial `host_port` ("host:port"). Synchronous, startup-connect style:
    /// blocks the calling thread until the connection succeeds or fails.
    fn dial(&mut self, host_port: &str) -> Result<(), DialError>;
    /// Bytes the far end has sent; `None` when none are available right now
    /// (this does not by itself mean the connection is down -- callers
    /// cross-check [`ModemTransport::carrier`] for that).
    fn read_byte(&mut self) -> Option<u8>;
    /// Cheap, non-blocking probe: would `read_byte` return data right now?
    fn has_pending(&self) -> bool;
    fn write_byte(&mut self, b: u8);
    /// Whether a carrier is currently up (connected).
    fn carrier(&self) -> bool;
    /// Idempotent: drop the connection if one is up.
    fn hangup(&mut self);
    /// Accept incoming calls on `addr` ("host:port"). Replaces any previous
    /// listener.
    fn listen(&mut self, addr: &str) -> io::Result<()>;
    /// An inbound caller is waiting, unanswered.
    fn ringing(&self) -> bool;
    /// Promote the waiting caller to the live connection. False when none
    /// is waiting (nobody is calling, or the caller hung up before being
    /// answered).
    fn answer(&mut self) -> bool;
    /// Drop the waiting caller without answering.
    fn reject(&mut self);
    /// Emulated-time tick, called from [`SerialSink::poll`] and once more
    /// from [`ModemSerialSink::enter_online`] with the connect moment's own
    /// `at_cck` (so a call-opening transport sees "now" immediately rather
    /// than waiting for the next poll). [`TcpModemTransport`] has nothing
    /// to time off emulated ticks (its pacing is real host time via
    /// [`SerialTimeAnchor`], like the rest of the network-backed sinks) and
    /// keeps the default no-op; [`session::ScriptedTransport`] is the one
    /// implementation that uses this, to gate its `delay` directives on the
    /// same clock `Settings::s12`'s guard time already uses.
    fn advance(&mut self, _at_cck: u64) {}
}

/// Spawn the background reader shared by every connected/accepted
/// [`TcpModemTransport`] state: pushes bytes into `tx` and bumps `buffered`
/// so the owning transport's `has_pending` stays a cheap atomic load, then
/// clears `writer` and `carrier` on EOF or error so the owner's next probe
/// sees the connection is gone.
fn spawn_modem_reader(
    mut stream: TcpStream,
    tx: std::sync::mpsc::Sender<u8>,
    buffered: Arc<AtomicIsize>,
    writer: Arc<Mutex<Option<TcpStream>>>,
    carrier: Arc<AtomicBool>,
) -> io::Result<()> {
    thread::Builder::new()
        .name("modem-tcp".into())
        .spawn(move || {
            let mut buf = [0u8; 512];
            loop {
                match stream.read(&mut buf) {
                    Ok(0) | Err(_) => break,
                    Ok(n) => {
                        for &b in &buf[..n] {
                            if tx.send(b).is_err() {
                                return;
                            }
                            buffered.fetch_add(1, Ordering::Release);
                        }
                    }
                }
            }
            *writer.lock().unwrap() = None;
            carrier.store(false, Ordering::Release);
        })?;
    Ok(())
}

/// The modem's real transport: dials out over TCP, reusing
/// [`crate::serial::TcpSerialSink`]'s reader-thread-plus-atomic-counter
/// pattern so Paula's idle fast path never touches a socket.
pub(crate) struct TcpModemTransport {
    rx: Option<std::sync::mpsc::Receiver<u8>>,
    /// Write half of the live connection, `None` when nothing is connected.
    /// Cleared by [`spawn_modem_reader`] on disconnect and by
    /// [`TcpModemTransport::write_byte`] on a failed write, mirroring
    /// `TcpSerialSink`.
    writer: Arc<Mutex<Option<TcpStream>>>,
    /// Bytes staged in `rx`; signed for the same transient-debt reason as
    /// `TcpSerialSink::buffered` (a `read_byte` racing ahead of the reader
    /// thread's `fetch_add` dips to -1 rather than wrapping huge).
    buffered: Arc<AtomicIsize>,
    /// Mirrors "the writer slot is occupied", kept as its own flag so
    /// `carrier()` is a plain atomic load rather than a mutex lock on
    /// Paula-facing hot paths (`control_lines`, `has_pending_input`).
    carrier: Arc<AtomicBool>,
    /// Inbound connection accepted by the `listen()` thread and parked here
    /// until `answer()` promotes it or `reject()` drops it. `None` when
    /// nobody is calling in.
    pending: Arc<Mutex<Option<TcpStream>>>,
    /// Mirrors "`pending` is occupied", kept as its own flag for the same
    /// atomic-load-only reason as `carrier`: `ringing()` is on the same
    /// Paula-facing footing as `carrier()`.
    ringing: Arc<AtomicBool>,
    /// The address `listen()` actually bound (a port of 0 resolves here).
    /// Test-only accessor, mirroring `TcpSerialSink::local_addr`.
    listen_addr: Option<SocketAddr>,
}

impl TcpModemTransport {
    /// A transport with nothing connected yet -- the emulator's
    /// dial-on-demand starting state.
    pub(crate) fn new() -> Self {
        Self {
            rx: None,
            writer: Arc::new(Mutex::new(None)),
            buffered: Arc::new(AtomicIsize::new(0)),
            carrier: Arc::new(AtomicBool::new(false)),
            pending: Arc::new(Mutex::new(None)),
            ringing: Arc::new(AtomicBool::new(false)),
            listen_addr: None,
        }
    }

    /// The address [`ModemTransport::listen`] actually bound. Test-only:
    /// production callers pass an explicit port (or accept the default),
    /// only tests bind port 0 and need to learn what they got.
    #[cfg_attr(not(test), allow(dead_code))]
    pub(crate) fn listen_addr(&self) -> Option<SocketAddr> {
        self.listen_addr
    }
}

impl ModemTransport for TcpModemTransport {
    fn dial(&mut self, host_port: &str) -> Result<(), DialError> {
        let addr = host_port
            .to_socket_addrs()
            .ok()
            .and_then(|mut it| it.next());
        let connect_result = match addr {
            Some(a) => TcpStream::connect_timeout(&a, Duration::from_secs(5)),
            None => TcpStream::connect(host_port),
        };
        let stream = connect_result.map_err(|e| match e.kind() {
            io::ErrorKind::ConnectionRefused => DialError::Refused,
            _ => DialError::Unreachable,
        })?;
        let _ = stream.set_nodelay(true);
        let writer_clone = stream.try_clone().map_err(|_| DialError::Unreachable)?;
        let (tx, rx) = std::sync::mpsc::channel();
        *self.writer.lock().unwrap() = Some(writer_clone);
        self.carrier.store(true, Ordering::Release);
        self.rx = Some(rx);
        spawn_modem_reader(
            stream,
            tx,
            Arc::clone(&self.buffered),
            Arc::clone(&self.writer),
            Arc::clone(&self.carrier),
        )
        .map_err(|_| DialError::Unreachable)?;
        Ok(())
    }

    fn read_byte(&mut self) -> Option<u8> {
        let b = self.rx.as_ref()?.try_recv().ok();
        if b.is_some() {
            self.buffered.fetch_sub(1, Ordering::Release);
        }
        b
    }

    fn has_pending(&self) -> bool {
        self.buffered.load(Ordering::Acquire) > 0
    }

    fn write_byte(&mut self, b: u8) {
        let mut guard = self.writer.lock().unwrap();
        if let Some(w) = guard.as_mut() {
            if w.write_all(&[b]).is_err() {
                *guard = None;
                drop(guard);
                self.carrier.store(false, Ordering::Release);
            }
        }
    }

    fn carrier(&self) -> bool {
        self.carrier.load(Ordering::Acquire)
    }

    fn hangup(&mut self) {
        if let Some(stream) = self.writer.lock().unwrap().take() {
            let _ = stream.shutdown(Shutdown::Both);
        }
        self.carrier.store(false, Ordering::Release);
    }

    fn listen(&mut self, addr: &str) -> io::Result<()> {
        let listener = TcpListener::bind(addr)?;
        let local_addr = listener.local_addr()?;
        let pending = Arc::new(Mutex::new(None));
        let ringing = Arc::new(AtomicBool::new(false));
        let (accept_pending, accept_ringing, accept_carrier) = (
            Arc::clone(&pending),
            Arc::clone(&ringing),
            Arc::clone(&self.carrier),
        );
        thread::Builder::new()
            .name("modem-tcp-listen".into())
            .spawn(move || {
                loop {
                    let Ok((stream, _peer)) = listener.accept() else {
                        return;
                    };
                    // The phone-line-busy analogue: a call is live, or an
                    // earlier caller is still parked unanswered, so this
                    // one gets connection-then-close -- the fast-busy tone
                    // an auto-dialer reads as BUSY, never a ring.
                    if accept_carrier.load(Ordering::Acquire)
                        || accept_ringing.load(Ordering::Acquire)
                    {
                        drop(stream);
                        continue;
                    }
                    let _ = stream.set_nodelay(true);
                    *accept_pending.lock().unwrap() = Some(stream);
                    accept_ringing.store(true, Ordering::Release);
                }
            })?;
        // Replaces whatever `listen()` bound before: a previous listener
        // thread (if any) is left running against its own now-orphaned
        // `pending`/`ringing`, harmless since nothing reads them anymore.
        self.pending = pending;
        self.ringing = ringing;
        self.listen_addr = Some(local_addr);
        Ok(())
    }

    fn ringing(&self) -> bool {
        self.ringing.load(Ordering::Acquire)
    }

    fn answer(&mut self) -> bool {
        let Some(stream) = self.pending.lock().unwrap().take() else {
            return false;
        };
        self.ringing.store(false, Ordering::Release);
        // A caller that hung up while waiting leaves a closed socket
        // parked; a zero-length peek reads EOF without consuming any real
        // data, so a dead parked stream is caught here instead of handing
        // the guest a CONNECT that drops on the next byte.
        let _ = stream.set_nonblocking(true);
        let mut probe = [0u8; 1];
        let dead = matches!(stream.peek(&mut probe), Ok(0));
        let _ = stream.set_nonblocking(false);
        if dead {
            return false;
        }
        let Ok(clone) = stream.try_clone() else {
            return false;
        };
        let (tx, rx) = std::sync::mpsc::channel();
        *self.writer.lock().unwrap() = Some(clone);
        self.rx = Some(rx);
        self.carrier.store(true, Ordering::Release);
        if spawn_modem_reader(
            stream,
            tx,
            Arc::clone(&self.buffered),
            Arc::clone(&self.writer),
            Arc::clone(&self.carrier),
        )
        .is_err()
        {
            *self.writer.lock().unwrap() = None;
            self.carrier.store(false, Ordering::Release);
            return false;
        }
        true
    }

    fn reject(&mut self) {
        if let Some(stream) = self.pending.lock().unwrap().take() {
            let _ = stream.shutdown(Shutdown::Both);
        }
        self.ringing.store(false, Ordering::Release);
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Mode {
    Command,
    Online,
}

/// A withheld `+++` escape candidate mid-flight. See
/// [`ModemSerialSink::handle_online_byte`] for the full state machine; kept
/// this small (a count and one timestamp) because all withheld bytes are
/// the same S2 character, so there is nothing else to remember.
#[derive(Clone, Copy)]
struct Escape {
    /// Escape characters accepted so far, 1..=3.
    count: u8,
    /// `at_cck` of the most recently accepted escape character.
    last_cck: u64,
    /// `count` has reached 3 and we are waiting out the trailing guard.
    awaiting_trail: bool,
}

#[derive(Clone, Copy)]
struct Settings {
    /// ATEn: echo guest command-mode bytes back to the guest.
    echo: bool,
    /// ATVn: verbose ("\r\nOK\r\n") vs numeric ("0\r") result codes.
    verbose: bool,
    /// ATQn: suppress all result codes.
    quiet: bool,
    /// S0: rings to wait through before auto-answering an inbound call; 0
    /// (default) disables auto-answer, ATA is then the only way to answer.
    s0: u8,
    /// S2: the `+++` escape character.
    s2: u8,
    /// S3: the command-line terminator [`ModemSerialSink::command_mode_write`]
    /// waits for. Default 13 (CR) -- almost nothing reprograms this, but a
    /// real modem honours it, so this one does too.
    s3: u8,
    /// S4: the response linefeed character, paired with S3 as the `<CR><LF>`
    /// every result code, S-register readback, and RING is framed in
    /// (verbose mode); numeric mode uses S3 alone. Default 10 (LF).
    s4: u8,
    /// S9 (WiModem232 extra): connect-detect response time, tenths of a
    /// second of *host* time -- [`ModemSerialSink::enter_online`] withholds
    /// remote-to-guest bytes until this long after CONNECT, the pause
    /// dialer-era terminal software (Terminate and kin) expects before BBS
    /// output starts. 0 (default) withholds nothing.
    s9: u8,
    /// S12: escape guard time, in fiftieths of a second.
    s12: u8,
    /// AT&Cn: n=0 means /CD reports asserted regardless of carrier state
    /// ("DCD always"); the default (n=1) tracks the real carrier.
    dcd_always: bool,
    /// AT&Dn: only 2 (default) and 3 are modeled -- both hang up on a
    /// DTR true->false transition. 0 and 1 are accepted but ignored (no
    /// auto-answer to disable, and &D1's escape-to-command-without-hangup
    /// behaviour is not modeled).
    dtr_action: u8,
    /// AT*T0/AT*T1 (WiModem232 extra): telnet NVT translation, engaged in
    /// [`ModemSerialSink::enter_online`] when true. 0/false is the default,
    /// matching the manual and leaving raw byte services untouched.
    telnet: bool,
    /// AT*P (WiModem232 extra): the port `ATD`/`ATDT` appends to a bare
    /// host (or a phonebook entry) with no `:port` of its own. Also the
    /// hardcoded M1 fallback, so the default (23) matches that unchanged.
    default_port: u16,
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            echo: true,
            verbose: true,
            quiet: false,
            s0: 0,
            s2: b'+',
            s3: b'\r',
            s4: b'\n',
            s9: 0,
            s12: 50,
            dcd_always: false,
            dtr_action: 2,
            telnet: false,
            default_port: 23,
        }
    }
}

/// Baud values `AT*B` accepts, per the WiModem232 manual; anything else is
/// ERROR. Real hardware would retarget its own UART to this rate -- ours
/// cannot (Paula's SERPER always governs the wire), so the value only ever
/// reaches [`ModemSerialSink::queue_result`]'s CONNECT text.
const STAR_B_BAUDS: [u32; 15] = [
    75, 110, 150, 300, 600, 1200, 2400, 4800, 9600, 14400, 19200, 38400, 57600, 115200, 230400,
];

enum ResultCode {
    Ok,
    Connect,
    NoCarrier,
    Error,
    Busy,
}

/// A Hayes-compatible modem sitting on Paula's serial port. Paula paces all
/// bytes at the SERPER rate through [`crate::serial::SerialSink::write_byte`]
/// / `read_byte`; this sink never paces, sleeps, or blocks -- the dial
/// transport does its own I/O on a background thread (see
/// [`TcpModemTransport`]).
pub struct ModemSerialSink {
    transport: Box<dyn ModemTransport>,
    mode: Mode,
    /// Command-mode line buffer, capped at [`MAX_LINE_LEN`].
    line: Vec<u8>,
    settings: Settings,
    /// Last rate reported via [`crate::serial::SerialSink::baud_changed`],
    /// quoted back in the CONNECT text.
    last_baud: Option<u32>,
    /// Modem-generated bytes (echo, result codes) waiting for the guest.
    out_queue: VecDeque<u8>,
    /// In-progress `+++` escape candidate, if any. Only meaningful while
    /// `mode` is `Online`.
    escape: Option<Escape>,
    /// `at_cck` of the most recent guest activity while online (an ordinary
    /// forwarded byte, an escape character, or the CONNECT that entered
    /// online mode) -- the reference point a new escape candidate's lead
    /// guard is measured from.
    last_online_activity_cck: Option<u64>,
    /// Previous DTR level, to detect a true->false transition in
    /// [`crate::serial::SerialSink::set_control_outputs`]. `None` until the
    /// first call, so the very first report (whatever it says) is never
    /// itself treated as a drop.
    dtr_prev: Option<bool>,
    /// A call is up (dialed, answered, or parked in command mode behind a
    /// `+++` escape with the line still connected) and this sink has not
    /// yet told the guest it dropped. Set on every transition into
    /// [`ModemSerialSink::enter_online`], cleared the moment NO CARRIER is
    /// reported for it (by [`SerialSink::poll`] catching a silent drop in
    /// command mode, by the online-mode remote-close path in
    /// [`SerialSink::read_byte`], or by [`ModemSerialSink::hangup_internal`]
    /// ending the call locally).
    carrier_expected: bool,
    /// S1: rings answered by RING since the last decay or hangup, readable
    /// and writable via ATS1. Real Hayes modems drift it back to 0 eight
    /// seconds after the last ring even with no call resolved either way;
    /// [`ModemSerialSink::poll`] applies that decay from `last_ring_cck`.
    s1: u8,
    /// `at_cck` of the most recently sent RING, `None` when nothing is
    /// currently ringing and S1 has already decayed. The reference point
    /// for both the ring cadence and the S1 decay timer.
    last_ring_cck: Option<u64>,
    /// `AT*B<baud>`'s stored value, quoted in CONNECT text ahead of
    /// `last_baud` when set (see [`Self::queue_result`]); `None` means
    /// nothing overrides the guest's own SERPER-derived rate. Not part of
    /// [`Settings`] because it is not part of the stored profile either
    /// (`profile::ModemProfile` has no baud field) and `AT&F` clears it
    /// while `ATZ` leaves it alone, the opposite of every `Settings` field.
    star_baud: Option<u32>,
    /// `[serial.phonebook]`, carried in from [`ModemOptions`] at
    /// construction: an all-digit `ATD`/`ATDT` target is looked up here
    /// before falling back to NO CARRIER (see [`Self::do_dial`]).
    phonebook: Vec<(String, String)>,
    /// Whether [`ModemOptions::telnet`] was `true` -- the only value that
    /// unambiguously means "the config explicitly turned telnet on" (see
    /// [`ModemOptions::telnet`]'s doc comment). Reapplied over a reloaded
    /// profile on every `ATZ`, alongside [`Self::new_tcp`]'s construction-time
    /// use of it, so the config keeps winning across a soft reset too.
    telnet_config_explicit: bool,
    /// The host half of whatever address inbound calls are (or were)
    /// answered on, so `AT*L<port>` can rebind to the same interface with
    /// just a new port. `"0.0.0.0"` when nothing has bound yet -- a guest
    /// that issues `AT*L` on a modem with no configured `[serial] listen`
    /// still gets to become answerable, the same as a real modem is always
    /// answerable given a phone line.
    listen_host: String,
    /// The port inbound calls are currently answered on, `None` if the
    /// modem has never listened. Persisted by `AT&W` as
    /// `profile::ModemProfile::listen_port`; changed at runtime by `AT*L`.
    listen_port: Option<u16>,
    /// The emulated-to-host time mapping ([`crate::serial::SerialTimeAnchor`]),
    /// last published by the emulator's own re-anchoring. `None` in tests
    /// that never call [`SerialSink::set_time_anchor`] -- S9's delay is then
    /// simply never enforced, the safe default for a fake transport with no
    /// host clock to speak of.
    time_anchor: Option<SerialTimeAnchor>,
    /// The host [`Instant`] before which remote-to-guest bytes stay
    /// withheld after CONNECT (S9's delay); `None` once elapsed, hangup, or
    /// while offline. See [`Self::connect_delay_pending`].
    connect_delay_until: Option<Instant>,
    /// The telnet NVT layer for the current call, present only while
    /// `Settings::telnet` was true at the moment [`Self::enter_online`] ran
    /// (`AT*T1`/`[serial] telnet` engages it; `AT*T0` bypasses it entirely
    /// rather than merely disabling translation mid-call). `None` means
    /// every byte crosses the wire unmodified.
    telnet: Option<telnet::TelnetNvt>,
    /// Decoded remote bytes ready for the guest, staged by
    /// [`Self::pump_telnet_input`] so a telnet negotiation exchange (which
    /// can consume several wire bytes to produce zero, or produce a reply
    /// that goes back out on the wire rather than to the guest) fits
    /// [`SerialSink::read_byte`]'s one-byte-at-a-time contract. With no
    /// telnet layer engaged this is just a one-hop relay of raw transport
    /// bytes, so the same pump serves both cases.
    telnet_out_to_guest: VecDeque<u8>,
}

impl ModemSerialSink {
    /// The emulator's constructor: dial is always on-demand via ATD;
    /// `options.listen` additionally binds an answering side at startup, so
    /// inbound calls can RING and be picked up (ATA, or S0 auto-answer).
    /// Propagates a bind failure with `?`, the same convention
    /// [`crate::serial::TcpSerialSink::listen`] uses -- a modem that was
    /// asked to answer calls and silently cannot is worse than a config
    /// error at startup.
    pub fn new_tcp(options: ModemOptions) -> anyhow::Result<Self> {
        let mut transport = TcpModemTransport::new();
        let sidecar = profile::ModemProfile::load();
        let listen_host = options
            .listen
            .as_deref()
            .and_then(|addr| addr.rsplit_once(':'))
            .map(|(host, _)| host.to_string())
            .unwrap_or_else(|| "0.0.0.0".to_string());
        let configured_port = options
            .listen
            .as_deref()
            .and_then(|addr| addr.rsplit_once(':'))
            .and_then(|(_, port)| port.parse().ok());
        // An explicit `[serial] listen` address always wins (it names both
        // host and port); with none, a stored `AT*L` port from a previous
        // session still makes the modem answerable -- the sidecar cannot
        // know a host, so it gets every interface.
        let listen_port = configured_port.or_else(|| sidecar.as_ref().and_then(|p| p.listen_port));
        let bind_addr = match (&options.listen, listen_port) {
            (Some(addr), _) => Some(addr.clone()),
            (None, Some(port)) => Some(format!("{listen_host}:{port}")),
            (None, None) => None,
        };
        if let Some(addr) = bind_addr.as_deref() {
            transport.listen(addr)?;
        }
        let mut sink = Self::with_transport(Box::new(transport));
        sink.phonebook = options.phonebook;
        sink.telnet_config_explicit = options.telnet;
        sink.listen_host = listen_host;
        sink.listen_port = listen_port;
        sink.settings = settings_from_sidecar(sidecar.as_ref(), sink.telnet_config_explicit);
        Ok(sink)
    }

    /// The determinism-story constructor: replays `path` (see
    /// `src/modem/session.rs`'s module doc comment for the file format)
    /// instead of dialing out over TCP, so a headless run driving this
    /// modem is byte-for-byte reproducible. `options.listen` is not
    /// consulted -- the scripted transport has no inbound side (see
    /// [`session::ScriptedTransport::listen`]) -- but `phonebook` and
    /// `telnet` behave exactly as they do for [`Self::new_tcp`], since an
    /// `ATD<number>` or `AT*T1` in the script's `expect` text still has to
    /// resolve/engage the same way a real session's would.
    pub fn new_scripted(path: &Path, options: ModemOptions) -> anyhow::Result<Self> {
        let transport = session::ScriptedTransport::load(path)?;
        let sidecar = profile::ModemProfile::load();
        let mut sink = Self::with_transport(Box::new(transport));
        sink.phonebook = options.phonebook;
        sink.telnet_config_explicit = options.telnet;
        sink.settings = settings_from_sidecar(sidecar.as_ref(), sink.telnet_config_explicit);
        Ok(sink)
    }

    pub(crate) fn with_transport(transport: Box<dyn ModemTransport>) -> Self {
        Self {
            transport,
            mode: Mode::Command,
            line: Vec::new(),
            settings: Settings::default(),
            last_baud: None,
            out_queue: VecDeque::new(),
            escape: None,
            last_online_activity_cck: None,
            dtr_prev: None,
            carrier_expected: false,
            s1: 0,
            last_ring_cck: None,
            star_baud: None,
            phonebook: Vec::new(),
            telnet_config_explicit: false,
            listen_host: "0.0.0.0".to_string(),
            listen_port: None,
            time_anchor: None,
            connect_delay_until: None,
            telnet: None,
            telnet_out_to_guest: VecDeque::new(),
        }
    }

    fn queue_out_byte(&mut self, b: u8) {
        if self.out_queue.len() == OUT_QUEUE_CAPACITY {
            self.out_queue.pop_front();
        }
        self.out_queue.push_back(b);
    }

    /// S3/S4 as a two-byte `<CR><LF>` pair, the line break every verbose
    /// response, S-register readback, RING, and the identity banner is
    /// framed in -- default `\r\n`, but a guest that reprograms S3/S4 (rare,
    /// but real hardware honours it) changes what actually goes out here.
    fn crlf(&self) -> [u8; 2] {
        [self.settings.s3, self.settings.s4]
    }

    fn queue_result(&mut self, code: ResultCode) {
        if self.settings.quiet {
            return;
        }
        let bytes = if self.settings.verbose {
            let s = match code {
                ResultCode::Ok => "OK".to_string(),
                // AT*B's stored value quotes the CONNECT text first, since
                // it is the guest's explicit statement of what it thinks
                // the line runs at; the SERPER-derived last_baud is only a
                // fallback for a guest that never set it.
                ResultCode::Connect => match self.star_baud.or(self.last_baud) {
                    Some(bps) => format!("CONNECT {bps}"),
                    None => "CONNECT".to_string(),
                },
                ResultCode::NoCarrier => "NO CARRIER".to_string(),
                ResultCode::Error => "ERROR".to_string(),
                ResultCode::Busy => "BUSY".to_string(),
            };
            let crlf = self.crlf();
            [&crlf[..], s.as_bytes(), &crlf[..]].concat()
        } else {
            let n = match code {
                ResultCode::Ok => "0",
                ResultCode::Connect => "1",
                ResultCode::NoCarrier => "3",
                ResultCode::Error => "4",
                ResultCode::Busy => "7",
            };
            // Numeric mode terminates with S3 alone, no S4 -- meant for
            // machine parsing, never carried a linefeed on real hardware.
            [n.as_bytes(), &[self.settings.s3]].concat()
        };
        for b in bytes {
            self.queue_out_byte(b);
        }
    }

    fn queue_identity(&mut self) {
        // ATIn: an identity banner. Real modems vary it by n; M1 has no
        // product line to differentiate, so every digit gets the same
        // short string. Not a "result code", so not gated by ATQ1.
        let crlf = self.crlf();
        let bytes: Vec<u8> = [&crlf[..], b"Copperline modem", &crlf[..]].concat();
        for b in bytes {
            self.queue_out_byte(b);
        }
    }

    fn queue_s_read(&mut self, reg: u8) {
        let val = match reg {
            0 => self.settings.s0,
            1 => self.s1,
            2 => self.settings.s2,
            3 => self.settings.s3,
            4 => self.settings.s4,
            9 => self.settings.s9,
            12 => self.settings.s12,
            _ => 0,
        };
        let crlf = self.crlf();
        let bytes: Vec<u8> = [&crlf[..], val.to_string().as_bytes(), &crlf[..]].concat();
        for b in bytes {
            self.queue_out_byte(b);
        }
    }

    fn set_s_register(&mut self, reg: u8, val: u8) {
        match reg {
            0 => self.settings.s0 = val,
            1 => self.s1 = val,
            2 => self.settings.s2 = val,
            3 => self.settings.s3 = val,
            4 => self.settings.s4 = val,
            9 => self.settings.s9 = val,
            12 => self.settings.s12 = val,
            // Every other S register is a stub: no state, no error, just an
            // accepted write (real modems have dozens few programs touch).
            _ => {}
        }
    }

    /// `AT&F`: hardcoded factory defaults, ignoring both the stored profile
    /// and any config override -- stock Hayes `AT&F` semantics, no
    /// exceptions. Also resets `AT*B`'s stored baud (the manual: "Baud rate
    /// is reset to 300"); ours has nothing to reset it *to* (Paula's SERPER
    /// still governs the wire), so it clears the override back to "defer to
    /// the guest's own rate" instead.
    fn reset_defaults(&mut self) {
        self.settings = Settings::default();
        self.star_baud = None;
    }

    /// `ATZ`: reload the stored profile (an explicit `[serial] telnet =
    /// true` still wins, same as at construction -- see
    /// [`ModemOptions::telnet`]'s doc comment), or hardcoded defaults with
    /// nothing stored. Deliberately leaves `star_baud` untouched: the
    /// manual is explicit that `ATZ` does not change the baud rate.
    fn reload_profile_settings(&mut self) {
        let sidecar = profile::ModemProfile::load();
        self.settings = settings_from_sidecar(sidecar.as_ref(), self.telnet_config_explicit);
    }

    /// `AT&W`: persist the currently active settings as the stored profile.
    /// A no-op on disk when persistence is off ([`profile::set_persistence`]),
    /// same as `profile::ModemProfile::save`'s own contract.
    fn save_profile(&self) {
        profile::ModemProfile {
            echo: self.settings.echo,
            verbose: self.settings.verbose,
            quiet: self.settings.quiet,
            s0: self.settings.s0,
            s2: self.settings.s2,
            s3: self.settings.s3,
            s4: self.settings.s4,
            s9: self.settings.s9,
            s12: self.settings.s12,
            dcd_always: self.settings.dcd_always,
            dtr_action: self.settings.dtr_action,
            telnet: self.settings.telnet,
            listen_port: self.listen_port,
            default_port: self.settings.default_port,
        }
        .save();
    }

    /// Idempotent hangup: drops the transport connection and, if a call was
    /// in progress, returns to command mode. Shared by ATH, ATZ/AT&F, and a
    /// DTR-drop with AT&D2/3. Also the one place S1/ring state resets on
    /// "the call is over", per Hayes convention (the other is the 8-second
    /// decay in [`ModemSerialSink::poll`]).
    fn hangup_internal(&mut self) {
        self.transport.hangup();
        self.escape = None;
        self.mode = Mode::Command;
        self.carrier_expected = false;
        self.s1 = 0;
        self.last_ring_cck = None;
        self.telnet = None;
        self.telnet_out_to_guest.clear();
        self.connect_delay_until = None;
    }

    /// Guard time in color clocks: S12 is in fiftieths of a second, and one
    /// fiftieth is `PAULA_CLOCK_HZ / 50` color clocks.
    fn guard_ccks(&self) -> u64 {
        u64::from(self.settings.s12) * u64::from(PAULA_CLOCK_HZ) / 50
    }

    /// Enter online (relay) mode after a successful ATD, an answered
    /// inbound call (ATA or S0 auto-answer), or an ATO with carrier up.
    /// `at_cck` becomes the escape lead-guard's reference point -- an
    /// escape cannot start until S12 of silence has passed since.
    fn enter_online(&mut self, at_cck: u64) {
        self.mode = Mode::Online;
        self.escape = None;
        self.last_online_activity_cck = Some(at_cck);
        self.carrier_expected = true;
        self.s1 = 0;
        self.last_ring_cck = None;
        // AT*T1 (or [serial] telnet's power-on default) engages the NVT
        // layer for this call only; AT*T0 leaves every byte untouched.
        self.telnet = self.settings.telnet.then(|| telnet::TelnetNvt::new(true));
        self.telnet_out_to_guest.clear();
        // S9, in host time: nothing withheld with no time anchor published
        // yet (tests with a fake transport that never calls
        // set_time_anchor) or with S9 at its default of 0.
        self.connect_delay_until = self.time_anchor.map(|anchor| {
            anchor.host_time(at_cck) + Duration::from_millis(u64::from(self.settings.s9) * 100)
        });
        // Gives a transport that times itself off emulated ticks (the
        // scripted session) the connect moment right away, rather than
        // waiting for the next `SerialSink::poll` -- see
        // `ModemTransport::advance`'s doc comment.
        self.transport.advance(at_cck);
        self.queue_result(ResultCode::Connect);
    }

    fn do_dial(&mut self, target: &[u8], at_cck: u64) {
        if self.transport.carrier() {
            // A guest that escaped to command mode with a call still up
            // and then dials again means "hang up and place a new call" --
            // the old line does not stay parked in the background while a
            // second one is placed.
            self.transport.hangup();
        }
        let target = String::from_utf8_lossy(target);
        let target = target.trim();
        // An all-digit target is a "phone number": WiModem232's phonebook
        // convention, resolved through [serial.phonebook] rather than
        // dialed literally (there is no DNS entry for a phone number).
        // Hayes has no notion of a phonebook to conflict with here.
        let host_port = if !target.is_empty() && target.bytes().all(|b| b.is_ascii_digit()) {
            let Some((_, addr)) = self.phonebook.iter().find(|(number, _)| number == target) else {
                self.queue_result(ResultCode::NoCarrier);
                return;
            };
            resolve_dial_addr(addr, self.settings.default_port)
        } else if target.contains(':') {
            target.to_string()
        } else {
            format!("{target}:{}", self.settings.default_port)
        };
        match self.transport.dial(&host_port) {
            Ok(()) => self.enter_online(at_cck),
            Err(DialError::Refused) => self.queue_result(ResultCode::Busy),
            Err(DialError::Unreachable) => self.queue_result(ResultCode::NoCarrier),
        }
    }

    fn do_answer(&mut self, at_cck: u64) {
        if self.transport.carrier() {
            // Same reasoning as `do_dial`: answering while a call is
            // already up drops it first rather than leaving it parked.
            self.transport.hangup();
        }
        if self.transport.answer() {
            self.enter_online(at_cck);
        } else {
            self.queue_result(ResultCode::NoCarrier);
        }
    }

    /// Ring cadence and RING/S0/S1 bookkeeping, driven by [`Self::poll`].
    /// Real Hayes modems ring roughly every four seconds of line time and
    /// give S1 the same eight-second decay a real line's ring-counter
    /// register carries between calls.
    fn poll_ring(&mut self, at_cck: u64) {
        const RING_CADENCE_CCKS: u64 = 4 * PAULA_CLOCK_HZ as u64;
        const S1_DECAY_CCKS: u64 = 8 * PAULA_CLOCK_HZ as u64;
        const RING_ABANDON_COUNT: u8 = 10;

        if self.mode == Mode::Command && self.transport.ringing() {
            let due = match self.last_ring_cck {
                None => true,
                Some(last) => at_cck.saturating_sub(last) >= RING_CADENCE_CCKS,
            };
            if due {
                self.queue_ring();
                self.last_ring_cck = Some(at_cck);
                self.s1 = self.s1.saturating_add(1);
                if self.s1 >= RING_ABANDON_COUNT {
                    // The exchange gives up on a call nobody picked up,
                    // same as a real line timing out an unanswered ring.
                    self.transport.reject();
                } else if self.settings.s0 > 0 && self.s1 >= self.settings.s0 {
                    self.do_answer(at_cck);
                }
            }
        }
        // S1 drifts back to 0 eight seconds after the last ring whether or
        // not that call was ever picked up.
        if let Some(last) = self.last_ring_cck {
            if at_cck.saturating_sub(last) >= S1_DECAY_CCKS {
                self.s1 = 0;
                self.last_ring_cck = None;
            }
        }
    }

    fn queue_ring(&mut self) {
        if self.settings.quiet {
            return;
        }
        let bytes: Vec<u8> = if self.settings.verbose {
            let crlf = self.crlf();
            [&crlf[..], b"RING", &crlf[..]].concat()
        } else {
            vec![b'2', self.settings.s3]
        };
        for b in bytes {
            self.queue_out_byte(b);
        }
    }

    /// Parse and execute one complete AT command line (without the
    /// terminating CR). Hayes chains commands left to right on one line
    /// (`ATE0V1` is legal), so this walks the bytes after the "AT" prefix
    /// once, dispatching each recognized letter in turn. The first
    /// malformed command aborts the rest of the line with ERROR, matching
    /// real Hayes behaviour.
    fn execute_line(&mut self, line: &[u8], at_cck: u64) {
        if line.is_empty() {
            // A bare CR in command mode gets no response.
            return;
        }
        let text = String::from_utf8_lossy(line);
        let upper = text.to_ascii_uppercase();
        let Some(rest) = upper.strip_prefix("AT") else {
            self.queue_result(ResultCode::Error);
            return;
        };
        let bytes = rest.as_bytes();
        let mut i = 0;
        // Set when a command already queued its own terminal result
        // (CONNECT/BUSY/NO CARRIER from D/O), so the line doesn't also get
        // a trailing OK.
        let mut terminal_result = false;
        while i < bytes.len() {
            match bytes[i] as char {
                'E' => {
                    let (v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.settings.echo = v != 0;
                    i = ni;
                }
                'Q' => {
                    let (v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.settings.quiet = v != 0;
                    i = ni;
                }
                'V' => {
                    let (v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.settings.verbose = v != 0;
                    i = ni;
                }
                'Z' => {
                    let (_v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.reload_profile_settings();
                    self.hangup_internal();
                    i = ni;
                }
                'H' => {
                    let (_v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.hangup_internal();
                    i = ni;
                }
                'O' => {
                    let (_v, ni) = read_digit_default(bytes, i + 1, 0);
                    if self.transport.carrier() {
                        self.enter_online(at_cck);
                    } else {
                        self.queue_result(ResultCode::NoCarrier);
                    }
                    terminal_result = true;
                    i = ni;
                }
                'I' => {
                    let (_v, ni) = read_digit_default(bytes, i + 1, 0);
                    self.queue_identity();
                    i = ni;
                }
                'A' => {
                    self.do_answer(at_cck);
                    terminal_result = true;
                    i += 1;
                }
                'D' => {
                    let mut j = i + 1;
                    if j < bytes.len() && matches!(bytes[j] as char, 'T' | 'P') {
                        j += 1;
                    }
                    let target = &bytes[j..];
                    self.do_dial(target, at_cck);
                    terminal_result = true;
                    i = bytes.len();
                }
                '&' => {
                    if i + 1 >= bytes.len() {
                        self.queue_result(ResultCode::Error);
                        return;
                    }
                    match bytes[i + 1] as char {
                        'F' => {
                            self.reset_defaults();
                            self.hangup_internal();
                            i += 2;
                        }
                        'C' => {
                            let (v, ni) = read_digit_default(bytes, i + 2, 1);
                            self.settings.dcd_always = v == 0;
                            i = ni;
                        }
                        'D' => {
                            let (v, ni) = read_digit_default(bytes, i + 2, 2);
                            self.settings.dtr_action = v;
                            i = ni;
                        }
                        'W' => {
                            let (_v, ni) = read_digit_default(bytes, i + 2, 0);
                            self.save_profile();
                            i = ni;
                        }
                        _ => {
                            self.queue_result(ResultCode::Error);
                            return;
                        }
                    }
                }
                'S' => {
                    let start = i + 1;
                    let mut j = start;
                    while j < bytes.len() && bytes[j].is_ascii_digit() {
                        j += 1;
                    }
                    if j == start {
                        self.queue_result(ResultCode::Error);
                        return;
                    }
                    let reg: u8 = std::str::from_utf8(&bytes[start..j])
                        .unwrap()
                        .parse()
                        .unwrap_or(0);
                    if j < bytes.len() && bytes[j] as char == '?' {
                        self.queue_s_read(reg);
                        i = j + 1;
                    } else if j < bytes.len() && bytes[j] as char == '=' {
                        let vstart = j + 1;
                        let mut k = vstart;
                        while k < bytes.len() && bytes[k].is_ascii_digit() {
                            k += 1;
                        }
                        if k == vstart {
                            self.queue_result(ResultCode::Error);
                            return;
                        }
                        let val: u8 = std::str::from_utf8(&bytes[vstart..k])
                            .unwrap()
                            .parse()
                            .unwrap_or(0);
                        self.set_s_register(reg, val);
                        i = k;
                    } else {
                        self.queue_result(ResultCode::Error);
                        return;
                    }
                }
                // The WiModem232 extended set. Each `AT*` command here takes
                // the rest of the line (like 'D' above): `AT*NS<n>,<pass>`'s
                // password has no other delimiter, and a guide always issues
                // one `AT*` command per line in practice, so there is
                // nothing real to chain after it. Every arm either queues
                // its own output before falling through, or just updates
                // `self.settings`/state and lets the trailing OK below speak
                // for it, matching the '&' block's convention.
                '*' => {
                    let rest = &bytes[i + 1..];
                    let ok = match rest.first().copied().map(|c| c as char) {
                        Some('B') => self.set_star_baud(&rest[1..]),
                        Some('T') => self.set_star_telnet(&rest[1..]),
                        Some('L') => self.set_star_listen_port(&rest[1..]),
                        Some('P') => self.set_star_default_port(&rest[1..]),
                        Some('N') if rest.get(1).map(|b| *b as char) == Some('S') => {
                            self.star_ns(&rest[2..])
                        }
                        Some('N') => {
                            self.queue_star_n();
                            true
                        }
                        Some('R') if rest == b"REBOOT" => {
                            // Resets the state machine like ATZ (reload the
                            // stored profile, drop any call); meaningless
                            // under emulation otherwise, present so a
                            // WiModem232 guide's setup script does not error
                            // out mid-run when it issues this for real.
                            self.reload_profile_settings();
                            self.hangup_internal();
                            true
                        }
                        _ => false,
                    };
                    if !ok {
                        self.queue_result(ResultCode::Error);
                        return;
                    }
                    i = bytes.len();
                }
                _ => {
                    self.queue_result(ResultCode::Error);
                    return;
                }
            }
        }
        if !terminal_result {
            self.queue_result(ResultCode::Ok);
        }
    }

    /// `AT*B<baud>[,<config>]`: stores the value for CONNECT text only (see
    /// `Settings::default_port`'s sibling `star_baud` field's doc comment);
    /// the manual's optional data-bits/parity/stop-bits `<config>` suffix is
    /// accepted and ignored -- there is no serial line configuration here
    /// beyond what Paula's SERPER already dictates.
    fn set_star_baud(&mut self, arg: &[u8]) -> bool {
        let baud_part = match arg.iter().position(|&b| b == b',') {
            Some(comma) => &arg[..comma],
            None => arg,
        };
        let Some(baud) = parse_all_digits::<u32>(baud_part) else {
            return false;
        };
        if !STAR_B_BAUDS.contains(&baud) {
            return false;
        }
        self.star_baud = Some(baud);
        true
    }

    /// `AT*T0`/`AT*T1`: telnet NVT translation, engaged for the next call
    /// [`Self::enter_online`] makes (not the one already up, if any --
    /// matches the manual's own "no re-negotiation mid-call" silence on the
    /// point). Any nonzero digit counts as 1, matching every other Hayes
    /// boolean argument in this module.
    fn set_star_telnet(&mut self, arg: &[u8]) -> bool {
        let Some(v) = parse_all_digits::<u32>(arg) else {
            return false;
        };
        self.settings.telnet = v != 0;
        true
    }

    /// `AT*L<port>`: rebinds inbound calls to the same host
    /// [`Self::listen_host`] already answers on (or `0.0.0.0` if it never
    /// has) with the new port. A bind failure (port already in use, no
    /// permission) is ERROR, not a silent no-op -- a sysop who mistypes a
    /// port should hear about it immediately, not discover it when nothing
    /// ever rings.
    fn set_star_listen_port(&mut self, arg: &[u8]) -> bool {
        let Some(port) = parse_all_digits::<u16>(arg) else {
            return false;
        };
        if self
            .transport
            .listen(&format!("{}:{port}", self.listen_host))
            .is_err()
        {
            return false;
        }
        self.listen_port = Some(port);
        true
    }

    /// `AT*P<port>`: the port `ATD`/`ATDT` (and a portless phonebook entry)
    /// appends to a bare host from now on.
    fn set_star_default_port(&mut self, arg: &[u8]) -> bool {
        let Some(port) = parse_all_digits::<u16>(arg) else {
            return false;
        };
        self.settings.default_port = port;
        true
    }

    /// `AT*NS<n>,<passphrase>`: "join network `n` from the last `AT*N`
    /// scan". There is no real Wi-Fi to join, so this only validates the
    /// syntax (a present, all-digit `n`) and succeeds -- plausible enough
    /// that a guide script that issues it does not error out mid-run, per
    /// the proposal's "WiFi-management commands stubbed plausibly" rule.
    fn star_ns(&mut self, arg: &[u8]) -> bool {
        let number_part = match arg.iter().position(|&b| b == b',') {
            Some(comma) => &arg[..comma],
            None => arg,
        };
        parse_all_digits::<u32>(number_part).is_some()
    }

    /// `AT*N`: lists the networks "in range". Real hardware scans Wi-Fi;
    /// there is nothing to scan under emulation, so this reports exactly
    /// one synthetic network in the manual's own listing format, enough for
    /// a guide script's `AT*N` step to see plausible output rather than an
    /// empty list.
    fn queue_star_n(&mut self) {
        for line in [
            "\r\nScanning available networks:\r\n",
            "\r\nNetworks available: 1\r\n",
            "\r\n0 - Copperline (-50 dBm), WPA2\r\n",
        ] {
            for b in line.bytes() {
                self.queue_out_byte(b);
            }
        }
    }

    fn command_mode_write(&mut self, b: u8, at_cck: u64) {
        if self.settings.echo {
            self.queue_out_byte(b);
        }
        if b == self.settings.s3 {
            let line = std::mem::take(&mut self.line);
            self.execute_line(&line, at_cck);
            return;
        }
        if self.line.len() >= MAX_LINE_LEN {
            self.line.clear();
            self.queue_result(ResultCode::Error);
            return;
        }
        self.line.push(b);
    }

    fn forward_escape_chars(&mut self, count: u8) {
        for _ in 0..count {
            self.transport_send(self.settings.s2);
        }
    }

    /// One guest byte outbound: through the telnet NVT layer (IAC-escaping
    /// it, among other things) when `AT*T1` engaged one for this call,
    /// otherwise straight to the transport untouched.
    fn transport_send(&mut self, b: u8) {
        match self.telnet.as_mut() {
            Some(nvt) => {
                let mut out = Vec::new();
                nvt.send(b, &mut out);
                for ob in out {
                    self.transport.write_byte(ob);
                }
            }
            None => self.transport.write_byte(b),
        }
    }

    /// Drain every wire byte currently available from the transport through
    /// the telnet layer (if one is engaged), staging decoded data in
    /// [`Self::telnet_out_to_guest`] and writing negotiation replies
    /// straight back out. A no-op call when nothing is pending, so callers
    /// can run it unconditionally before checking the queue.
    fn pump_telnet_input(&mut self) {
        while self.transport.has_pending() {
            let Some(b) = self.transport.read_byte() else {
                break;
            };
            match self.telnet.as_mut() {
                Some(nvt) => {
                    let mut data = Vec::new();
                    let mut reply = Vec::new();
                    nvt.receive(b, &mut data, &mut reply);
                    self.telnet_out_to_guest.extend(data);
                    for r in reply {
                        self.transport.write_byte(r);
                    }
                }
                None => self.telnet_out_to_guest.push_back(b),
            }
        }
    }

    /// S9's connect delay, in host time: true while remote-to-guest bytes
    /// must stay withheld. Always false with no time anchor published (a
    /// fake-transport test that never called `set_time_anchor`) -- the
    /// delay is host-clock-driven by design (see `Settings::s9`'s doc
    /// comment), so it has nothing to measure against otherwise.
    fn connect_delay_pending(&self) -> bool {
        matches!(self.connect_delay_until, Some(until) if Instant::now() < until)
    }

    /// The `+++` escape state machine. Deterministic and `at_cck`-only --
    /// never host time. Hayes semantics: at least S12 of guest silence,
    /// then exactly three S2 characters each within S12 of the previous,
    /// then S12 of guest silence with nothing else sent drops to command
    /// mode (carrier stays up; ATO returns online) and reports OK. Anything
    /// else -- a non-escape byte, a fourth escape char, or a gap violating
    /// either window -- forwards the withheld escape characters plus the
    /// offending byte and the relay continues.
    ///
    /// The trailing guard is normally completed by [`Self::poll`], which is
    /// driven purely by elapsed `at_cck` and needs no further guest byte to
    /// notice the guard has expired -- a guest that falls silent right
    /// after `+++` still drops to command mode on schedule. This method's
    /// own `awaiting_trail` branch stays as a same-call fallback for direct
    /// callers that drive `write_byte` without ever calling `poll` (this
    /// module's own unit tests): a guest byte landing after the guard has
    /// elapsed is itself treated as the first character of a new command
    /// line rather than being relayed.
    fn handle_online_byte(&mut self, b: u8, at_cck: u64) {
        if let Some(e) = self.escape.take() {
            let guard = self.guard_ccks();
            let gap = at_cck.saturating_sub(e.last_cck);
            if e.awaiting_trail {
                if gap >= guard {
                    self.mode = Mode::Command;
                    self.queue_result(ResultCode::Ok);
                    self.command_mode_write(b, at_cck);
                } else {
                    self.forward_escape_chars(e.count);
                    self.transport_send(b);
                    self.last_online_activity_cck = Some(at_cck);
                }
                return;
            }
            if b == self.settings.s2 && gap <= guard {
                let mut e = e;
                e.count += 1;
                e.last_cck = at_cck;
                if e.count == 3 {
                    e.awaiting_trail = true;
                }
                self.escape = Some(e);
            } else if b == self.settings.s2 {
                // The withheld chars sat idle for a full guard time before
                // this byte arrived, so that silence is itself a valid lead
                // guard: this byte starts a fresh candidate rather than
                // joining (or busting) the old one.
                self.forward_escape_chars(e.count);
                self.escape = Some(Escape {
                    count: 1,
                    last_cck: at_cck,
                    awaiting_trail: false,
                });
            } else {
                self.forward_escape_chars(e.count);
                self.transport_send(b);
            }
            self.last_online_activity_cck = Some(at_cck);
            return;
        }

        let guard = self.guard_ccks();
        let lead_ok = matches!(
            self.last_online_activity_cck,
            Some(prev) if at_cck.saturating_sub(prev) >= guard
        );
        if b == self.settings.s2 && lead_ok {
            self.escape = Some(Escape {
                count: 1,
                last_cck: at_cck,
                awaiting_trail: false,
            });
        } else {
            self.transport_send(b);
        }
        self.last_online_activity_cck = Some(at_cck);
    }
}

/// The `Settings` a sidecar profile (or its absence) and the config's own
/// telnet key resolve to, per `profile.rs`'s documented precedence: an
/// explicit `[serial] telnet = true` always wins, everything else is the
/// sidecar's value if one loaded, else `Settings::default()`. A pure
/// function (no disk, no `PERSIST`) so it is directly unit-testable, unlike
/// `profile::ModemProfile::load`/`save` themselves (see `profile.rs`'s own
/// test doc comment for why those stay untested at the file level here).
fn settings_from_sidecar(
    sidecar: Option<&profile::ModemProfile>,
    telnet_explicit: bool,
) -> Settings {
    let mut settings = match sidecar {
        Some(p) => Settings {
            echo: p.echo,
            verbose: p.verbose,
            quiet: p.quiet,
            s0: p.s0,
            s2: p.s2,
            s3: p.s3,
            s4: p.s4,
            s9: p.s9,
            s12: p.s12,
            dcd_always: p.dcd_always,
            dtr_action: p.dtr_action,
            telnet: p.telnet,
            default_port: p.default_port,
        },
        None => Settings::default(),
    };
    if telnet_explicit {
        settings.telnet = true;
    }
    settings
}

/// A phonebook entry's address, filled out with the modem's default
/// outgoing port (`AT*P`) when the entry itself named no port -- the same
/// convention the manual's `AT&Z`/`AT&SN` phone-book-and-spoof entries use.
fn resolve_dial_addr(addr: &str, default_port: u16) -> String {
    if addr.contains(':') {
        addr.to_string()
    } else {
        format!("{addr}:{default_port}")
    }
}

/// A run of ASCII digits filling the whole slice; `None` if it is empty or
/// holds anything else. Used for the WiModem232 `AT*` numeric arguments
/// (`AT*B<baud>`, `AT*L<port>`, `AT*P<port>`), which -- unlike the base
/// Hayes single-digit arguments `read_digit_default` covers -- can be more
/// than one digit and have no sensible zero-argument default.
fn parse_all_digits<T: std::str::FromStr>(bytes: &[u8]) -> Option<T> {
    if bytes.is_empty() || !bytes.iter().all(u8::is_ascii_digit) {
        return None;
    }
    std::str::from_utf8(bytes).ok()?.parse().ok()
}

/// Read an optional run of ASCII digits starting at `i`; `default` when
/// none are present. Used for the single-digit arguments to E/Q/V/H/O/I/&C/
/// &D (`ATE` alone means `ATE0`, matching common Hayes practice of treating
/// an omitted numeric argument as 0).
fn read_digit_default(bytes: &[u8], i: usize, default: u8) -> (u8, usize) {
    if i < bytes.len() && bytes[i].is_ascii_digit() {
        let start = i;
        let mut j = i;
        while j < bytes.len() && bytes[j].is_ascii_digit() {
            j += 1;
        }
        let v = std::str::from_utf8(&bytes[start..j])
            .unwrap()
            .parse()
            .unwrap_or(default);
        (v, j)
    } else {
        (default, i)
    }
}

impl SerialSink for ModemSerialSink {
    fn write_byte(&mut self, b: u8, at_cck: u64) {
        match self.mode {
            Mode::Online => self.handle_online_byte(b, at_cck),
            Mode::Command => self.command_mode_write(b, at_cck),
        }
    }

    fn read_byte(&mut self) -> Option<u8> {
        if let Some(b) = self.out_queue.pop_front() {
            return Some(b);
        }
        if self.mode == Mode::Online {
            if !self.transport.carrier() {
                // The remote end closed the connection: surface it to the
                // guest and fall back to command mode, same as a real modem
                // losing carrier mid-call. Not gated by S9 -- that delay is
                // about withholding a live line's output, not about hiding
                // that the line went away.
                self.hangup_internal();
                self.queue_result(ResultCode::NoCarrier);
                return self.out_queue.pop_front();
            }
            if self.connect_delay_pending() {
                return None;
            }
            self.pump_telnet_input();
            return self.telnet_out_to_guest.pop_front();
        }
        None
    }

    fn has_pending_input(&self) -> bool {
        if !self.out_queue.is_empty() {
            return true;
        }
        if self.mode == Mode::Online {
            // A dropped carrier also counts as "pending": the next
            // `read_byte` call turns it into a queued NO CARRIER.
            if !self.transport.carrier() {
                return true;
            }
            if self.connect_delay_pending() {
                return false;
            }
            return !self.telnet_out_to_guest.is_empty() || self.transport.has_pending();
        }
        false
    }

    fn can_produce_input(&self) -> bool {
        true
    }

    /// Escape trailing-guard completion, a dropped-carrier NO CARRIER in
    /// command mode, and RING/S0/S1 bookkeeping -- everything this sink
    /// times off elapsed line time rather than a guest byte. See
    /// [`Self::handle_online_byte`] and [`Self::poll_ring`] for the two
    /// halves' own reasoning.
    fn poll(&mut self, at_cck: u64) {
        self.transport.advance(at_cck);
        if self.mode == Mode::Online {
            if let Some(e) = self.escape {
                if e.awaiting_trail && at_cck.saturating_sub(e.last_cck) >= self.guard_ccks() {
                    self.mode = Mode::Command;
                    self.escape = None;
                    self.queue_result(ResultCode::Ok);
                }
            }
        }
        if self.mode == Mode::Command && self.carrier_expected && !self.transport.carrier() {
            // A call parked in command mode behind a `+++` escape whose
            // remote end drops: nothing else polls the transport while
            // idle in command mode, so without this the guest would never
            // learn the line went away short of trying ATO.
            self.carrier_expected = false;
            self.queue_result(ResultCode::NoCarrier);
        }
        self.poll_ring(at_cck);
    }

    fn reset_after_timeline_jump(&mut self) {
        // The line dropped, but the modem itself was not reset: settings
        // are retained, only the call and any in-flight state go away.
        self.transport.reject();
        self.hangup_internal();
        self.line.clear();
        self.out_queue.clear();
        self.last_online_activity_cck = None;
    }

    fn machine_reset(&mut self) {
        // A full ATZ: the stored profile reloads (or hardcoded defaults
        // with nothing stored), call dropped -- same as the guest typing
        // ATZ itself, since a real modem cannot tell "the terminal program
        // sent ATZ" apart from "the host computer's reset button was hit".
        self.reload_profile_settings();
        self.transport.reject();
        self.hangup_internal();
        self.line.clear();
        self.out_queue.clear();
        self.last_online_activity_cck = None;
        self.dtr_prev = None;
    }

    fn flush(&mut self) {}

    fn set_time_anchor(&mut self, anchor: SerialTimeAnchor) {
        self.time_anchor = Some(anchor);
    }

    fn control_lines(&self) -> Option<u8> {
        // /DSR and /CTS are always asserted (this sink never models flow
        // control or a missing terminal). Active-low: asserted = 0 bit.
        let mut bits = 0u8;
        let cd_asserted = self.transport.carrier() || self.settings.dcd_always;
        if !cd_asserted {
            bits |= 1 << 5; // /CD deasserted -> wire high
        }
        Some(bits)
    }

    fn set_control_outputs(&mut self, dtr: bool, rts: bool) {
        let _ = rts; // accepted, unused (no hardware flow control modeled)
        let was_asserted = self.dtr_prev.replace(dtr);
        if was_asserted == Some(true) && !dtr && matches!(self.settings.dtr_action, 2 | 3) {
            self.hangup_internal();
            self.queue_result(ResultCode::NoCarrier);
        }
    }

    fn baud_changed(&mut self, bps: u32) {
        self.last_baud = Some(bps);
    }
}

